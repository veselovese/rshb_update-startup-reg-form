create table digital_content.file_request
(
    id         bigint generated by default as identity primary key,
    submit_dt  timestamp    not null,
    file_id    bigint       null     default null,
    full_name  varchar(255) not null,
    position   varchar(255) null     default null,
    phone      varchar(15)  not null,
    email      varchar(254) not null,
    org        varchar(255) null     default null,
    suspicious bool         not null default false,

    constraint file_id_fk
        foreign key (file_id)
            references digital_content.shared_files_index (id)
            on delete set null
);

alter table digital_content.shared_files_index
    add column dnld_limit int not null default 2;

alter table digital_content.shared_files_index
    add column ext_notif_templ_id bigint null default null;

alter table digital_content.shared_files_index
    add foreign key (ext_notif_templ_id)
        references digital_notifications.templates (id)
        on delete set null;

