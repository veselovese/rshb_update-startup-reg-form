CREATE TABLE digital_contest_chef.o_plt_chef_contestants
(

    id              bigint               NOT NULL generated by default as identity,
    submit_date     timestamp            NOT NULL,
    contestant_name varchar(300)         NOT NULL,
    phone           varchar(15)          NOT NULL UNIQUE,
    result          varchar(255)         NOT NULL,
    solution_url    varchar(1000) UNIQUE NOT NULL,

    CONSTRAINT o_plt_chef_contestants_pk
        PRIMARY KEY (id)
);

CREATE TABLE digital_contest_chef.o_plt_chef_notification_receiver
(
    id      bigint              NOT NULL generated by default as identity,
    name    varchar(300)        NOT NULL,
    email   varchar(320) UNIQUE NOT NULL,
    enabled boolean             NOT NULL DEFAULT true,
    deleted boolean             NOT NULL DEFAULT false,

    CONSTRAINT o_plt_chef_notification_receiver_pk
        PRIMARY KEY (id)
);