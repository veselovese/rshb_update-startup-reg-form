create table digital_statistics.agrobit_salary_position_category
(
    id          bigint generated by default as identity,
    external_id varchar(100) not null,
    title       varchar(255) not null,
    enabled     boolean      not null default true,

    constraint agrobit_salary_cat_pk
        primary key (id)
);

create table digital_statistics.agrobit_salary_position
(
    id          bigint generated by default as identity,
    external_id varchar(100) not null,
    title       varchar(255) not null,
    enabled     boolean      not null default true,

    constraint agrobit_salary_pos_pk
        primary key (id)
);

create table digital_statistics.agrobit_salary_pos_to_cat
(
    id     bigint generated by default as identity,
    cat_id bigint not null,
    pos_id bigint not null,

    constraint agrobit_salary_pos_to_cat_pk
        primary key (id),

    constraint agrobit_salary_pos_to_cat_cat_fk
        foreign key (cat_id)
            references digital_statistics.agrobit_salary_position_category (id)
            on delete cascade,

    constraint agrobit_salary_pos_to_cat_pos_fk
        foreign key (pos_id)
            references digital_statistics.agrobit_salary_position (id)
            on delete cascade
);

