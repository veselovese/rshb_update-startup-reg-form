CREATE TABLE digital_feedback.o_plt_feedback_reports
(
    id            bigint        NOT NULL generated by default as identity,
    submit_date   timestamp     NULL,
    reporter_name varchar(300)  NULL,
    email         varchar(320)  NOT NULL,
    phone         varchar(15)   NULL,
    feedback      varchar(1000) NOT NULL,
    log           varchar(1000),

    CONSTRAINT o_plt_feedback_reports_pk
        PRIMARY KEY (id)
);

CREATE TABLE digital_feedback.o_plt_notification_receivers
(
    id      bigint              NOT NULL generated by default as identity,
    name    varchar(300)        NOT NULL,
    email   varchar(320) UNIQUE NOT NULL,
    enabled boolean             NOT NULL DEFAULT true,
    deleted boolean             NOT NULL DEFAULT false,

    CONSTRAINT o_plt_notification_receivers_pk
        PRIMARY KEY (id)
);