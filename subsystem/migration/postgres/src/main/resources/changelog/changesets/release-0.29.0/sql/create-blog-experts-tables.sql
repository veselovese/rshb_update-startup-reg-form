create table digital_blogs.expert_registration
(
    id               bigint generated by default as identity,
    submit_date      timestamp     not null,
    expert_name      varchar(255)  not null,
    email            varchar(254)  not null,
    phone            varchar(15)   not null,
    vk_url           varchar(2048) not null,
    directions       varchar(255)  not null,
    performance_urls text          null,
    comment          varchar(1000) not null,

    constraint expert_registration_pk
        primary key (id)
);

create table digital_blogs.expert_direction_ref
(
    id          bigint generated by default as identity,
    external_id varchar(100) not null unique,
    title       varchar(255) not null,
    enabled     bool         not null default true,

    constraint expert_direction_ref_pk
        primary key (id)
);

