CREATE TABLE internship.o_plt_registration
(
    id                bigint        NOT NULL generated by default as identity,
    registration_date timestamp     NULL,
    applicant_name    varchar(1000) NOT NULL,
    internship_field  varchar(1000) NOT NULL,
    email             varchar(320)  NOT NULL,
    phone             varchar(15)   NOT NULL UNIQUE,
    about             varchar(1000) NULL,
    log               varchar(1000),

    CONSTRAINT o_plt_registration_pkey
        PRIMARY KEY (id)
);