create table digital_contests.stipend_question
(
    id             bigint generated by default as identity,
    submit_date    timestamp     not null,
    applicant_name varchar(255)  not null,
    email          varchar(254)  not null,
    phone          varchar(15)   not null,
    question       varchar(1000) not null,
    suspicious     boolean       not null default false,

    constraint stipend_questions_pk
        primary key (id)
);

create table digital_contests.stipend_task_solution
(
    id               bigint generated by default as identity,
    submit_date      timestamp     not null,
    participant_name varchar(255)  not null,
    task_id          varchar(255)  not null,
    email            varchar(254)  not null,
    phone            varchar(15)   not null,
    comment          varchar(1000) not null,
    suspicious       boolean       not null default false,

    constraint stipend_task_solution_pk
        primary key (id)
);

create table digital_contests.stipend_task
(
    id         bigint generated by default as identity,
    task_id    varchar(255) not null unique,
    task_title varchar(255) not null,
    enabled    boolean      not null default true,

    constraint stipend_task_pk
        primary key (id)
);

