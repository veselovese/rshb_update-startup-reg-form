CREATE TABLE digital_puzzles.o_plt_crosswords
(
    id          bigint       NOT NULL generated by default as identity,
    external_id varchar(100) NOT NULL unique,
    deleted     boolean      not null default false,

    CONSTRAINT o_plt_crosswords_pk
        PRIMARY KEY (id)
);

CREATE TABLE digital_puzzles.o_plt_crossword_to_category
(
    id     bigint NOT NULL generated by default as identity,
    cwd_id bigint not null,
    cat_id bigint not null,

    CONSTRAINT o_plt_cwd_to_cat_pk
        PRIMARY KEY (id),

    CONSTRAINT o_plt_cwd_to_cat_cwd_fk
        FOREIGN KEY (cwd_id)
            REFERENCES digital_puzzles.o_plt_crosswords (id)
            ON DELETE CASCADE,

    CONSTRAINT o_plt_cwd_to_cat_cat_fk
        FOREIGN KEY (cat_id)
            REFERENCES digital_puzzles.o_plt_crossword_categories (id)
            ON DELETE CASCADE
);

CREATE TABLE digital_puzzles.o_plt_cwd_questions
(
    id           bigint       NOT NULL generated by default as identity,
    external_id  varchar(100) NOT NULL unique,
    crossword_id bigint,
    title        varchar(255) not null,
    pos_row      bigint       not null,
    pos_column   bigint       not null,
    answer       varchar(255) not null,
    direction    varchar(10)  not null,

    CONSTRAINT o_plt_cwd_questions_pk
        PRIMARY KEY (id),

    CONSTRAINT o_plt_cwd_questions_cwd_fk
        FOREIGN KEY (crossword_id)
            REFERENCES digital_puzzles.o_plt_crosswords (id)
            ON DELETE CASCADE
)