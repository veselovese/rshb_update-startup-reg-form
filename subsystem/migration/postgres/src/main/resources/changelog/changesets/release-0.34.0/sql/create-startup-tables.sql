create table digital_startups.reg_showcase
(
    id               bigint generated by default as identity primary key,
    submit_dt        timestamp     not null,
    applicant_name   varchar(255)  not null,
    org              varchar(255)  not null,
    position         varchar(255)  null default null,
    email            varchar(254)  not null,
    phone            varchar(15)   not null,
    vk_url           varchar(2048) null default null,
    country_id       bigint        not null,
    city_id          bigint        not null,
    proj_title       varchar(255)  not null,
    proj_descr_short varchar(300)  not null,
    proj_descr_full  varchar(1000) not null,
    invest_val       bigint        null default null,
    invest_curr_id   bigint        null default null,
    cat_id           bigint        null,
    cat_custom       varchar(255)  null,
    founded_year     integer       not null,
    staff_size       integer       null default null,
    proj_stage_id    bigint        not null,
    clients_id       bigint        not null,
    fin_round_id     bigint        not null,
    suspicious       bool          not null,


    constraint reg_showcase_country_fk
        foreign key (country_id)
            references digital_refs.location_country (id)
            on delete cascade,

    constraint reg_showcase_city_fk
        foreign key (city_id)
            references digital_refs.location_city (id)
            on delete cascade,

    constraint reg_showcase_cat_fk
        foreign key (cat_id)
            references digital_startups.reg_cat_ref (id)
            on delete cascade,

    constraint reg_showcase_clients_fk
        foreign key (clients_id)
            references digital_startups.reg_clients_num_ref (id)
            on delete cascade,

    constraint reg_showcase_curr_fk
        foreign key (invest_curr_id)
            references digital_startups.reg_curr_ref (id)
            on delete cascade,

    constraint reg_showcase_fin_fk
        foreign key (fin_round_id)
            references digital_startups.reg_fin_round_ref (id)
            on delete cascade,

    constraint reg_showcase_proj_stg_fk
        foreign key (proj_stage_id)
            references digital_startups.reg_proj_stage_ref (id)
            on delete cascade
);
