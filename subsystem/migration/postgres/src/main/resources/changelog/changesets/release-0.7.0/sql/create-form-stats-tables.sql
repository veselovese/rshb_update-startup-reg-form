CREATE TABLE digital_statistics.o_plt_form_usage_reports
(
    id                bigint    NOT NULL generated by default as identity,
    created_date      timestamp not null,
    period_start_date timestamp not null,
    period_end_date   timestamp not null,

    CONSTRAINT o_plt_form_usage_reports_pk
        PRIMARY KEY (id)
);

CREATE TABLE digital_statistics.o_plt_form_usage_stats
(
    id        bigint       NOT NULL generated by default as identity,
    report_id bigint       not null,
    form_type varchar(100) not null,
    count     bigint       not null,
    delta     bigint       not null,
    total     bigint       not null,

    CONSTRAINT o_plt_form_usage_stats_pk
        PRIMARY KEY (id),

    CONSTRAINT o_plt_form_usage_stats_report_fk
        FOREIGN KEY (report_id)
            REFERENCES digital_statistics.o_plt_form_usage_reports (id)
            ON DELETE CASCADE
);

CREATE TABLE digital_statistics.o_plt_notification_receivers
(
    id      bigint              NOT NULL generated by default as identity,
    name    varchar(300)        NOT NULL,
    email   varchar(320) UNIQUE NOT NULL,
    enabled boolean             NOT NULL DEFAULT true,
    deleted boolean             NOT NULL DEFAULT false,

    CONSTRAINT o_plt_notification_receivers_pk
        PRIMARY KEY (id)
);