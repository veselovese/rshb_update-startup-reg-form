CREATE TABLE digital_innovations.o_plt_applicants
(
    id             bigint        NOT NULL generated by default as identity,
    submit_date    timestamp     NULL,
    applicant_name varchar(300)  NOT NULL,
    email          varchar(320)  NOT NULL,
    phone          varchar(15)   NOT NULL UNIQUE,
    about_proposal varchar(1000) NULL,
    log            varchar(1000),

    CONSTRAINT o_plt_applicants_pk
        PRIMARY KEY (id)
);

CREATE TABLE digital_innovations.o_plt_notification_receivers
(
    id      bigint              NOT NULL generated by default as identity,
    name    varchar(300)        NOT NULL,
    email   varchar(320) UNIQUE NOT NULL,
    enabled boolean             NOT NULL DEFAULT true,
    deleted boolean             NOT NULL DEFAULT false,

    CONSTRAINT o_plt_notification_receivers_pk
        PRIMARY KEY (id)
);
