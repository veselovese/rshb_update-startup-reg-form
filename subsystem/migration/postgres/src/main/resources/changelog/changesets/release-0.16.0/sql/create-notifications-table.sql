CREATE TABLE digital_notifications.recipients
(
    id        bigint generated by default as identity,
    "name"    varchar(300) NOT NULL,
    email     varchar(254) NOT NULL,
    "enabled" boolean      NOT NULL default true,
    deleted   boolean      NOT NULL default false,

    CONSTRAINT recipients_pk
        PRIMARY KEY (id)
);

CREATE TABLE digital_notifications.topics
(
    id             bigint generated by default as identity,
    topic_key      varchar(200) NOT NULL UNIQUE,
    email_template text         NOT NULL,
    "enabled"      boolean      NOT NULL default true,
    deleted        boolean      NOT NULL default false,

    CONSTRAINT topics_pk
        PRIMARY KEY (id)
);

CREATE TABLE digital_notifications.recipient_to_topic
(
    id           bigint generated by default as identity,
    recipient_id bigint NOT NULL,
    topic_id     bigint NOT NULL,

    CONSTRAINT recipient_to_topic_pk
        PRIMARY KEY (id),

    CONSTRAINT recipient_fk
        FOREIGN KEY (recipient_id)
            REFERENCES digital_notifications.recipients (id)
            ON DELETE CASCADE,

    CONSTRAINT topic_fk
        FOREIGN KEY (topic_id)
            REFERENCES digital_notifications.topics (id)
            ON DELETE CASCADE
);
