CREATE TABLE digital_innovations.o_plt_window_demands
(
    id           bigint        NOT NULL generated by default as identity,
    external_id  varchar(100)  NOT NULL unique,
    submit_date  timestamp     NOT NULL,
    company_name varchar(200)  NOT NULL,
    company_site varchar(500)  NOT NULL,
    summary      varchar(300)  NOT NULL,
    description  varchar(1000) NOT NULL,
    phone        varchar(15)   NOT NULL,
    email        varchar(254)  NOT NULL,

    CONSTRAINT o_plt_window_demands_pk
        PRIMARY KEY (id)
);

CREATE TABLE digital_innovations.o_plt_window_proposals
(
    id                  bigint        NOT NULL generated by default as identity,
    external_id         varchar(100)  NOT NULL unique,
    submit_date         timestamp     NOT NULL,
    demand_card_id      varchar(100)  NOT NULL,
    description         varchar(1000) NOT NULL,
    startup_link        varchar(500)  NULL,
    startup_name        varchar(200)  NOT NULL,
    representative_name varchar(200)  NOT NULL,
    phone               varchar(15)   NOT NULL,
    email               varchar(254)  NOT NULL,

    CONSTRAINT o_plt_window_proposals_pk
        PRIMARY KEY (id)
);