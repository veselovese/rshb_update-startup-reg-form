create table digital_statistics.agrobit_university
(
    id             bigint generated by default as identity primary key,
    uni_name       varchar(255) not null,
    uni_short_name varchar(100) not null,
    disabled       bool         not null default false
);

create table digital_statistics.agrobit_university_faculty
(
    id            bigint generated by default as identity primary key,
    university_id bigint       not null,
    fac_name      varchar(255) not null,
    edu_type      varchar(100) not null,

    constraint agrobit_university_faculty_uni_fk
        foreign key (university_id)
            references digital_statistics.agrobit_university (id)
            on delete cascade
);

create table digital_statistics.agrobit_university_year_stats
(
    id         bigint generated by default as identity primary key,
    year       bigint not null,
    stat_value bigint null default null,
    faculty_id bigint not null,

    constraint agrobit_university_year_stats_fac_fk
        foreign key (faculty_id)
            references digital_statistics.agrobit_university_faculty (id)
            on delete cascade
);
