CREATE TABLE digital_vacancies.o_plt_vacancies
(
    id               bigint         NOT NULL generated by default as identity,
    external_id      varchar(100)   NOT NULL unique,
    title            varchar(300)   NOT NULL,
    description      varchar(30000) NULL,
    description_html varchar(30000) NULL,
    publish_date     timestamp      NOT NULL,
    url              varchar(500)   NOT NULL,
    apply_url        varchar(500)   NOT NULL,
    company_id       bigint         NOT NULL,
    area_id          bigint         NOT NULL,
    employment_id    bigint         NOT NULL,
    experience_id    bigint         NOT NULL,
    deleted          boolean        NOT NULL default false,

    CONSTRAINT o_plt_vacancies_pk
        PRIMARY KEY (id),

    CONSTRAINT o_plt_vacancies_company_fk
        FOREIGN KEY (company_id)
            REFERENCES digital_vacancies.o_plt_companies (id)
            ON DELETE CASCADE,

    CONSTRAINT o_plt_vacancies_area_fk
        FOREIGN KEY (area_id)
            REFERENCES digital_vacancies.o_plt_areas (id)
            ON DELETE CASCADE,

    CONSTRAINT o_plt_vacancies_employment_fk
        FOREIGN KEY (employment_id)
            REFERENCES digital_vacancies.o_plt_employments
            ON DELETE CASCADE,

    CONSTRAINT o_plt_vacancies_experience_fk
        FOREIGN KEY (experience_id)
            REFERENCES digital_vacancies.o_plt_experience
            ON DELETE CASCADE
);

CREATE TABLE digital_vacancies.o_plt_specializations
(
    id             bigint       NOT NULL generated by default as identity,
    external_id    varchar(100) NOT NULL unique,
    title          varchar(300) NOT NULL,
    profarea_id    varchar(50)  NULL,
    profarea_title varchar(100) NULL,
    deleted        boolean      NOT NULL default false,

    CONSTRAINT o_plt_specializations_pk
        PRIMARY KEY (id)
);

CREATE TABLE digital_vacancies.o_plt_vacancy_to_specialization
(
    id                bigint NOT NULL generated by default as identity,
    vacancy_id        bigint NOT NULL,
    specialization_id bigint NOT NULL,

    CONSTRAINT o_plt_vac_to_spec_pk
        PRIMARY KEY (id),

    CONSTRAINT o_plt_vac_to_spec_vac_fk
        FOREIGN KEY (vacancy_id)
            REFERENCES digital_vacancies.o_plt_vacancies (id)
            ON DELETE CASCADE,

    CONSTRAINT o_plt_vac_to_spec_spec_fk
        FOREIGN KEY (specialization_id)
            REFERENCES digital_vacancies.o_plt_specializations (id)
            ON DELETE CASCADE
);

