CREATE TABLE digital_subscriptions.o_plt_subscriptions
(
    id                bigint       NOT NULL generated by default as identity,
    creation_date     timestamp    not null,
    activation_date   timestamp    null,
    deactivation_date timestamp    null,
    blocking_date     timestamp    null,
    renewal_date      timestamp    null,
    email             varchar(254) not null unique,
    activation_code   varchar(100) null,
    deactivation_code varchar(100) null,

    CONSTRAINT o_plt_subscriptions_pk
        PRIMARY KEY (id)
);

CREATE TABLE digital_subscriptions.o_plt_subscription_categories
(
    id          bigint       NOT NULL generated by default as identity,
    external_id varchar(100) NOT NULL unique,
    title       varchar(500) NOT NULL,
    cat_type    varchar(100) NOT NULL,
    deleted     boolean      not null default false,

    CONSTRAINT o_plt_subscription_categories_pk
        PRIMARY KEY (id)
);

