CREATE TABLE digital_subscriptions.o_plt_sub_to_cat_active
(
    id     bigint NOT NULL generated by default as identity,
    sub_id bigint NOT NULL,
    cat_id bigint NOT NULL,

    CONSTRAINT o_plt_sub_to_cat_active_pk
        PRIMARY KEY (id),

    CONSTRAINT o_plt_sub_to_cat_active_sub_fk
        FOREIGN KEY (sub_id)
            REFERENCES digital_subscriptions.o_plt_subscriptions (id)
            ON DELETE CASCADE,

    CONSTRAINT o_plt_sub_to_cat_active_cat_fk
        FOREIGN KEY (cat_id)
            REFERENCES digital_subscriptions.o_plt_subscription_categories (id)
            ON DELETE CASCADE
);

